import assert from 'node:assert/strict';
import { nextRestaurantOrderStatus, quoteRestaurantRoom, validateRestaurantCart } from '../src/modules/restaurant/restaurantJourney.js';
const menu = [{ id: 'dish', price: 10, stock: 2 }];
assert.equal(validateRestaurantCart([{ ...menu[0], quantity: 2 }], menu), '');
for (const quantity of [0, 3, 1.5, NaN]) assert.ok(validateRestaurantCart([{ ...menu[0], quantity }], menu));
assert.ok(validateRestaurantCart([{ id: 'dish', price: 5, quantity: 1 }], menu));
assert.ok(validateRestaurantCart([], menu));
const booking = { roomId: 'room', arrival: '2026-11-01', departure: '2026-11-03', guests: '2' };
const room = { id: 'room', available: true, price: 95, capacity: 2 };
const quote = (changes = {}, reservations = [], changedRoom = room) => quoteRestaurantRoom({ ...booking, ...changes }, changedRoom, reservations, '2026-10-19');
assert.deepEqual(quote(), { nights: 2, subtotal: 190, platformFee: 0, total: 190, currency: 'USD' });
for (const changes of [{ guests: '0' }, { guests: '3' }, { arrival: 'bad' }, { departure: booking.arrival }, { arrival: '2026-01-01' }]) assert.ok(quote(changes).error);
assert.ok(quote({}, [], { ...room, available: false }).error);
assert.ok(quote({}, [{ ...booking, type: 'room', status: 'requested' }]).error);
assert.equal(quote({}, [{ ...booking, type: 'room', status: 'cancelled' }]).error, undefined);
assert.equal(nextRestaurantOrderStatus('pending'), 'preparing');
assert.equal(nextRestaurantOrderStatus('preparing'), 'ready');
assert.equal(nextRestaurantOrderStatus('ready'), 'completed');
assert.equal(nextRestaurantOrderStatus('completed'), null);
console.log('Restaurant : validations panier, tarifs, chevauchements et transitions reussies.');
