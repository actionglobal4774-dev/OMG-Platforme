import assert from "node:assert/strict";
import { buildPayflowEvent, createPayflowJourneyStore } from "../src/services/payflowJourney.js";
const values = new Map();
const storage = { getItem: (key) => values.get(key) || null, setItem: (key, value) => values.set(key, value) };
const alice = createPayflowJourneyStore(storage, "alice");
const bob = createPayflowJourneyStore(storage, "bob");
assert.equal(alice.record({ reference: "PF-A", type: "request", amount: 4.99, currency: "USD", status: "awaiting_payment", live: true, pin: "1234", bankAccount: "SECRET", recipient: "PRIVATE", payload: { pin: "1234" } }).saved, true);
assert.equal(alice.read().length, 1);
assert.equal(bob.read().length, 0);
for (const secret of ["1234", "SECRET", "PRIVATE", "payload", "pin"]) assert.ok(!JSON.stringify(alice.read()).includes(secret));
alice.record({ reference: "PF-A", status: "completed", live: true });
assert.equal(alice.read().length, 1);
assert.equal(alice.read()[0].status, "completed");
assert.equal(buildPayflowEvent({ reference: "PF-B", status: "invented" }).status, "prepared");
assert.equal(buildPayflowEvent({ reference: "PF-B", status: "completed", live: false }).status, "prepared");
assert.throws(() => buildPayflowEvent({ reference: "PF-B", amount: Infinity }));
assert.throws(() => buildPayflowEvent({ amount: 5 }));
assert.equal(createPayflowJourneyStore({ getItem: () => "corrupt", setItem() {} }, "a").read().length, 0);
assert.equal(createPayflowJourneyStore({ getItem: () => null, setItem() { throw Error("full"); } }, "a").record({ reference: "PF-C" }).saved, false);
console.log("Payflow : historique isolé par compte, références sans doublon, statuts et exclusion des secrets validés.");
