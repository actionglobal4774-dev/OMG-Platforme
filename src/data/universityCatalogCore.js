function enrichUniversityCatalogByCountry() {
  universityCatalog.countries = universityCatalog.countries.map((country) => {
    const faculties = Array.isArray(country.faculties) ? [...country.faculties] : [];
    const existingIds = new Set(faculties.map((faculty) => faculty.id));

    (countrySpecificFaculties[country.code] || []).forEach((faculty) => {
      if (!existingIds.has(faculty.id)) {
        faculties.push(faculty);
        existingIds.add(faculty.id);
      }
    });

    const coveredPrograms = new Set();

    faculties.forEach((faculty) => {
      (faculty.programs || []).forEach((programId) => coveredPrograms.add(programId));
    });

    mandatoryAdmissionPrograms.forEach((programId) => {
      if (!coveredPrograms.has(programId)) {
        faculties.push(buildSupplementalFaculty(country, programId));
        coveredPrograms.add(programId);
      }
    });

    globalAdmissionTrackTemplates.forEach((template, index) => {
      if (faculties.length >= minimumFacultyCoverage) {
        return;
      }

      const supplemental = buildGlobalAdmissionTrack(country, template, index);
      if (!existingIds.has(supplemental.id)) {
        faculties.push(supplemental);
        existingIds.add(supplemental.id);
        supplemental.programs.forEach((programId) => coveredPrograms.add(programId));
      }
    });

    return {
      ...country,
      faculties,
      coveredPrograms: Array.from(coveredPrograms),
      admissionCompleteness: "pays couvert par les principales filieres de concours"
    };
  });
}

enrichUniversityCatalogByCountry();

export function getCountryByCode(code) {
  return universityCatalog.countries.find((country) => country.code === code) || universityCatalog.countries[0];
}

export function getSubjectsForFaculties(countryCode, facultyIds) {
  const country = getCountryByCode(countryCode);
  const subjectIds = new Set();

  country.faculties
    .filter((faculty) => facultyIds.includes(faculty.id))
    .forEach((faculty) => {
      faculty.programs.forEach((programId) => {
        universityCatalog.programs[programId]?.subjects.forEach((subjectId) => subjectIds.add(subjectId));
      });
    });

  return Array.from(subjectIds).map((subjectId) => ({
    id: subjectId,
    ...universityCatalog.subjects[subjectId]
  }));
}

export function getUniversityCatalogStats() {
  const countries = universityCatalog.countries.length;
  const faculties = universityCatalog.countries.reduce((total, country) => total + country.faculties.length, 0);
  const subjects = Object.keys(universityCatalog.subjects).length;
  const chapters = Object.values(universityCatalog.subjects).reduce((total, subject) => total + subject.chapters.length, 0);
  return { countries, faculties, subjects, chapters };
}
